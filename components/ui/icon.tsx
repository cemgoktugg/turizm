/** İsimle lucide ikonu render eder; bilinmeyen isimlerde Sparkles gösterir */
export function Icon({
  name,
  ...props
}: { name: IconName | string | null | undefined } & Omit<LucideProps, "name">) {
  const Cmp = isIconName(name) ? REGISTRY[name] : Sparkles;
  return <Cmp {...props} />;
}
